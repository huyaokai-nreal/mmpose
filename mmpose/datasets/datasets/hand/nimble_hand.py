def get_nimble_bones_length():
    valid_joints = template_joints[kp_index]
    reshape_joints = np.zeros((5, 5, 3), np.float32)
    for i in range(5):
        reshape_joints[i, 0] = valid_joints[0]
    reshape_joints[:, 1:] = valid_joints[1:].reshape((5, 4, 3))
    bones = np.linalg.norm(
        reshape_joints[:, 1:] - reshape_joints[:, :-1], axis=-1) / 1000.0
    return bones
